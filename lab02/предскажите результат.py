#Прогноз до запуска

#Вычислим выражения вручную:


 #2 + 3 * 4 = 14
 #(2 + 3) * 4 = 20
 #17 // 5 = 3
 #17 % 5 = 2
 #-7 // 2 = -4

#Последний результат получается -4, потому что // округляет результат деления вниз, то есть к меньшему целому.


print(2 + 3 * 4)
print((2 + 3) * 4)
print(17 // 5)
print(17 % 5)
print(-7 // 2)



#Объяснение

#Результаты Python совпали с прогнозом.

#В выражении 2 + 3 * 4 сначала выполняется умножение, поэтому получается 2 + 12 = 14.

#17 // 5 даёт количество полных пятёрок — 3, а 17 % 5 даёт остаток — 2.

#Особенность -7 // 2: обычное деление даёт -3.5, а целочисленное деление // округляет вниз, поэтому результат равен -4.
